"""The Philadelphia Museum of Art, Main Building, as a curated Memory Blueprint plan.

`pma_plan.json` is generated by docs/building-palace/build_pma_plan.py from public sources only (see the plan's own `src`, each with its licence, and `n`): the 1928
Architectural Forum plan plates (public domain) traced into rooms, walls, doors, stairs and columns; the OpenStreetMap footprint (ODbL) for the shell; PMA-published
dimensions and gallery numbers read as facts (the visitor map and event plans are never traced). Levels follow the visitor map (G, 1, 2, 3).

What is sourced and what is assumed is in the plan itself: every element carries `c` (0-3) and `s`; rooms carry `x28` (changed since 1928), `gm` (how a gallery number was
matched or why it was left off) and `cand` (the unresolved candidate numbers); heights carry `hb`/`hc` (basis, confidence), almost all typed defaults at confidence 1.
"""
from __future__ import annotations

import copy
import json
from functools import lru_cache
from pathlib import Path

PLAN_FILE = Path(__file__).resolve().parent / "pma_plan.json"
ID = "pma"


@lru_cache(maxsize=1)
def _plan() -> dict:
    return json.loads(PLAN_FILE.read_text(encoding="utf-8"))


def plan() -> dict:
    """A fresh copy of the PMA plan (safe to modify)."""
    from . import pma_frames
    return pma_frames.merge(copy.deepcopy(_plan()))


def credits() -> list:
    """The credit lines the blueprint footer shows (the `cr` of each source)."""
    return [s["cr"] for s in _plan().get("src", []) if s.get("cr")]


def licences() -> list:
    """[(source id, title, licence)] of every source the plan cites."""
    return [(s["id"], s["t"], s.get("lic", "")) for s in _plan().get("src", [])]


def art_manifest() -> dict:
    from .pma_art import manifest
    return manifest()
